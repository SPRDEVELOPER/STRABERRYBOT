"""
Premium/custom emoji support.

Telegram lets a bot render *custom* (Premium-pack) emojis in message text
and captions by attaching CUSTOM_EMOJI entities on top of a normal unicode
placeholder emoji. Buttons (InlineKeyboardButton) do NOT support this at
all -- that's a hard Telegram Bot API limitation, not something fixable
here, so button labels always keep plain unicode emoji.

This module is applied automatically, bot-wide, by
`STRABERRY.utils.premium_patch` -- every plugin's reply_text/edit_text/
send_photo/etc. call is patched at the pyrogram Client level, so no
individual command file needs to import or call anything from here.
It's still safe to call `premium()` directly if you ever need it (e.g.
building a message by hand outside the normal send/edit path):

    from STRABERRY.utils.premium_emoji import premium

    text, entities = await premium(client, "\u2705 **Done!** \U0001F525 nice one")
    await message.reply_text(text, entities=entities)

`premium()` runs the text through Pyrogram's own parser first (so
**bold**/__italic__/<b>HTML</b>/etc. keep working, matching whatever
parse_mode the caller would otherwise have used), then overlays
CUSTOM_EMOJI entities on every recognised emoji character at its correct
UTF-16 offset. Every emoji that appears anywhere in this codebase is
recognised -- see EMOJI_MAP below -- so nothing is ever left as plain
unicode.
"""


def _utf16_len(s: str) -> int:
    """Telegram entity offsets/lengths are counted in UTF-16 code units,
    not python characters (matters for emoji outside the BMP)."""
    return len(s.encode("utf-16-le")) // 2


# Longest keys first, so a compound sequence like heart+VS16+ZWJ+fire is
# matched whole instead of accidentally matching a shorter sub-emoji first.
_SORTED_KEYS = sorted(EMOJI_MAP.keys(), key=len, reverse=True)


async def premium(
    client, text: str, mode: Optional[ParseMode] = None
) -> Tuple[str, List[MessageEntity]]:
    """Parse `text` the same way the caller's send/edit call would have
    (via `mode`, exactly as pyrogram's own parser would resolve it -- pass
    `None` to fall back to the client's own default parse_mode, same as
    every un-patched send_message/reply_text call already does), then
    overlay premium-emoji entities on top.

    Returns (parsed_text, entities) ready to pass straight into
    reply_text(text, entities=entities) / send_message(...) / edit_text(...).
    Do NOT also pass parse_mode when using the returned entities -- Telegram
    entities and parse_mode are mutually exclusive; the text is already
    parsed here.
    """
    parsed = await client.parser.parse(text, mode)
    parsed_text = parsed["message"]
    # `client.parser.parse()` returns raw MTProto entity objects (e.g.
    # `pyrogram.raw.types.MessageEntityBold`), not `pyrogram.types.MessageEntity`.
    # Those raw objects use `__slots__` with no `_client` slot, so once we hand
    # this list to `send_message(entities=...)`, pyrogram's
    # `parse_text_entities()` helper does `entity._client = client` on every
    # item and blows up with `AttributeError: '...' object has no attribute
    # '_client'`. Convert every raw entity to a proper `types.MessageEntity`
    # (same conversion pyrogram itself uses when building incoming messages)
    # before appending our own custom-emoji entities on top.
    raw_entities = parsed.get("entities") or []
    entities: List[MessageEntity] = [
        MessageEntity._parse(client, raw_entity, {}) for raw_entity in raw_entities
    ]
    for raw_entity, entity in zip(raw_entities, entities):
        if isinstance(raw_entity, raw.types.InputMessageEntityMentionName) and entity.user is None:
            entity.user = types.User(id=raw_entity.user_id.user_id, client=client)

    cursor = 0
    i = 0
    n = len(parsed_text)
    while i < n:
        matched_key = None
        for key in _SORTED_KEYS:
            if parsed_text.startswith(key, i):
                matched_key = key
                break

        if matched_key:
            ch_len = _utf16_len(matched_key)
            if not any(
                e.type == MessageEntityType.CUSTOM_EMOJI and e.offset == cursor
                for e in entities
            ):
                entities.append(
                    MessageEntity(
                        type=MessageEntityType.CUSTOM_EMOJI,
                        offset=cursor,
                        length=ch_len,
                        custom_emoji_id=EMOJI_MAP[matched_key],
                    )
                )
            cursor += ch_len
            i += len(matched_key)
        else:
            cursor += _utf16_len(parsed_text[i])
            i += 1

    entities.sort(key=lambda e: e.offset)
    return parsed_text, entities
